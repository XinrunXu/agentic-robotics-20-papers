def link(key):
    return f'<a href="extra-{key}.html">{escape(BY_KEY[key]["title"])}</a>'

def rows(spec):
    return [[g, link(k), y, use] for k, g, y, use in spec]

def preface(other_label, other_slug):
    note = '<p class="note">这些精读同样逐条回原文核对，实验数字都是作者报告；但它们不计入主线篇数，时间线仍是主线那一批。点表格里的标题进入精读，页面顶端会标出它属于哪一条支线。'
    note += f'另一条支线见<a href="{other_slug}">{other_label}</a>。</p>'
    return note

